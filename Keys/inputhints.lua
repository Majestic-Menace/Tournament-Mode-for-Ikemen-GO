function f_searchCmd(input, btntype)
	for i, v in ipairs(btntype) do --For each item in table
		if v.cmd == input then --if table cmd item is equal to input entered
			return i --Returns the position of the item in the table
		end
	end
	return nil --Returns nil if the item is not found in the table
end

function f_searchButton(inputkey) --Based on previous function
	for i, v in ipairs(t_sdlInputConvert) do
		if v.text == inputkey then
			return i
		end
	end
	return #t_sdlInputConvert --return lastest table value that is an empty spr
end

--Searches the gamepad table by button id ('0'..'13') or button name
--('A', 'LB'...). Returns the table position, or nil when unknown
--(caller falls back to the blank keyboard sprite, never a wrong icon).
function f_searchGamepadButton(inputkey)
	if inputkey == nil then return nil end
	local k = tostring(inputkey)
	for i, v in ipairs(t_xboxInputConvert) do
		if v.num == k then
			return i
		end
	end
	for i, v in ipairs(t_xboxInputConvert) do
		if string.lower(tostring(v.text)) == string.lower(k) then
			return i
		end
	end
	--SDL/common aliases (BACK = MENU button, DP_U = D-pad up, ...).
	local aliases = {
		dp_u = "up", dpup = "up",
		dp_d = "down", dpdown = "down",
		dp_l = "left", dpleft = "left",
		dp_r = "right", dpright = "right",
		back = "menu", select = "menu",
		leftshoulder = "lb", rightshoulder = "rb",
		lefttrigger = "lt", righttrigger = "rt",
		leftstick = "l3", rightstick = "r3",
	}
	local want = aliases[string.lower(k)]
	if want ~= nil then
		for i, v in ipairs(t_xboxInputConvert) do
			if string.lower(tostring(v.text)) == want then
				return i
			end
		end
	end
	return nil
end

--Resolves one key-config row (t_keyMenuCfg/t_keyBattleCfg entry with
--.keyboard/.gamepad) to group + table position.
--Gamepad (SFF group 1) wins when a gamepad id is set; otherwise keyboard
--(SFF group 0). Never returns nil: unknown ids fall back to the blank sprite.
function f_searchInputHint(entry)
	local gp = entry ~= nil and entry.gamepad or nil
	if gp ~= nil and tostring(gp) ~= "" then
		local btn = f_searchGamepadButton(gp)
		if btn ~= nil then return 1, btn end
	end
	local kb = entry ~= nil and entry.keyboard or ""
	return 0, f_searchButton(kb or "")
end

inputHintsCnt = 0
function drawMenuInputHints(...) --(...) Manage unlimited arguments
	local _legacyController = 0 --Unused: sprite group now comes from f_searchInputHint (0=keyboard, 1=gamepad)
	local t_control = nil
	if onlinegame then
		t_control = t_keyMenuCfg --Show only P1 Keys
	else
		if inputHintsCnt < 500 then
			t_control = t_keyMenuCfg
		else--if inputHintsCnt > 500 then
			t_control = t_keyMenuCfg2
		end
		if inputHintsCnt > 1000 then inputHintsCnt = 0 end --Reset
	end
	local t_args = {...} --Store all arguments taken in a table
	local customScaleX = keyboardInputHintsScaleX
	local customScaleY = keyboardInputHintsScaleY
--If the total number of arguments is odd, assume that the last one is a table with the custom scales {x, y}
	if #t_args % 2 ~= 0 then
		local scales = table.remove(t_args) --Extract and then remove last item of t_args table
		if type(scales) == "table" then
			customScaleX = scales[1] or keyboardInputHintsScaleX
			customScaleY = scales[2] or keyboardInputHintsScaleY
		end
	end
	for i=1, #t_args, 2 do --For each argument stored in table
		local cmd = t_args[i] --Set first argument (key name) to cmd var
		local cmdPos = t_args[i + 1] --Set second argument (keyX, keyY) to cmdPos var
		local nameKey = f_searchCmd(cmd, t_control) --get table pos from button name configured based on cmd entry name
		if nameKey ~= nil then
			local hintGroup, btn = f_searchInputHint(t_control[nameKey]) --Get button configured (group 0=keyboard, 1=gamepad)
			local keyID = tonumber((hintGroup == 1 and t_xboxInputConvert[btn].num or t_sdlInputConvert[btn].num)) --Reuse keyboard/gamepad IDs table
			local key = hintGroup..','..keyID..',0,0,-1' --Get button sprite (group 0=keyboard, 1=gamepad)
			key = animNew(sprInputHints, key) --Create sprite anim
			--local posKey = cmdPos --Get button "X,Y" positions
			local posKeyX, posKeyY = cmdPos:match('^([^,]-)%s*,%s*(.-)$') --Separate positions in vars
			animSetPos(key, posKeyX, posKeyY)
			if hintGroup == 1 then animSetScale(key, gamepadInputHintsScaleX, gamepadInputHintsScaleY) else animSetScale(key, customScaleX, customScaleY) end
			animUpdate(key)
			animDraw(key)
		end
	end
	if not onlinegame then
		inputHintsCnt = inputHintsCnt + 1
	end
end

